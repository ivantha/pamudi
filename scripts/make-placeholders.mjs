/**
 * Generates the placeholder cover art used by the sample case studies.
 *
 * These exist only so the scaffold renders as a real page before any of
 * Pamudi's actual work is in the repo. Delete this script, and the PNGs it
 * writes, as soon as real covers land — nothing in the site depends on it.
 *
 * Usage: node scripts/make-placeholders.mjs
 */
import { mkdir, writeFile } from "node:fs/promises"
import path from "node:path"
import sharp from "sharp"

const OUT = path.resolve("src/assets/work")
const W = 1600
const H = 1000

const PAPER = "#fbf9f4"
const PAPER2 = "#f1ede4"
const INK = "#16120d"
const RULE = "#e4ddd0"
const ACCENT = "#b8341a"

/** Abstract compositions, one per sample case study. */
const COMPOSITIONS = {
    "placeholder-01": `
        <rect width="${W}" height="${H}" fill="${PAPER2}"/>
        <g stroke="${RULE}" stroke-width="2">
            ${Array.from({ length: 11 }, (_, i) => `<line x1="${(i + 1) * (W / 12)}" y1="0" x2="${(i + 1) * (W / 12)}" y2="${H}"/>`).join("")}
        </g>
        <rect x="133" y="140" width="533" height="720" fill="${PAPER}"/>
        <rect x="133" y="140" width="533" height="96" fill="${INK}"/>
        <rect x="173" y="300" width="360" height="18" fill="${RULE}"/>
        <rect x="173" y="344" width="440" height="18" fill="${RULE}"/>
        <rect x="173" y="388" width="280" height="18" fill="${RULE}"/>
        <rect x="173" y="470" width="200" height="56" fill="${ACCENT}"/>
        <circle cx="1130" cy="500" r="270" fill="${ACCENT}"/>
        <path d="M860 500a270 270 0 0 1 270-270v270z" fill="${PAPER}"/>
    `,
    "placeholder-02": `
        <rect width="${W}" height="${H}" fill="${PAPER}"/>
        <rect x="0" y="0" width="${W}" height="220" fill="${INK}"/>
        <rect x="120" y="320" width="640" height="440" fill="${PAPER2}"/>
        <rect x="120" y="320" width="640" height="440" fill="none" stroke="${RULE}" stroke-width="3"/>
        <path d="M160 700 L300 560 L420 640 L560 430 L720 520" fill="none" stroke="${ACCENT}" stroke-width="10" stroke-linejoin="round" stroke-linecap="round"/>
        <g fill="${INK}">
            <rect x="860" y="320" width="620" height="14"/>
            <rect x="860" y="380" width="480" height="14"/>
            <rect x="860" y="440" width="560" height="14"/>
        </g>
        <rect x="860" y="540" width="620" height="220" fill="${PAPER2}" stroke="${RULE}" stroke-width="3"/>
        <circle cx="970" cy="650" r="52" fill="${ACCENT}"/>
    `,
    "placeholder-03": `
        <rect width="${W}" height="${H}" fill="${INK}"/>
        <rect x="90" y="90" width="${W - 180}" height="${H - 180}" fill="${PAPER}"/>
        <g transform="translate(90 90)">
            <rect x="0" y="0" width="${W - 180}" height="110" fill="${PAPER2}"/>
            ${Array.from({ length: 3 }, (_, i) => `<rect x="${60 + i * 460}" y="190" width="380" height="260" fill="${PAPER2}" stroke="${RULE}" stroke-width="3"/>`).join("")}
            ${Array.from({ length: 3 }, (_, i) => `<rect x="${60 + i * 460}" y="190" width="380" height="60" fill="${i === 1 ? ACCENT : RULE}"/>`).join("")}
            <rect x="60" y="530" width="1300" height="16" fill="${RULE}"/>
            <rect x="60" y="580" width="980" height="16" fill="${RULE}"/>
            <rect x="60" y="640" width="260" height="64" fill="${INK}"/>
        </g>
    `,
}

await mkdir(OUT, { recursive: true })

for (const [name, body] of Object.entries(COMPOSITIONS)) {
    const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${W}" height="${H}" viewBox="0 0 ${W} ${H}">${body}</svg>`
    const out = path.join(OUT, `${name}.png`)
    await sharp(Buffer.from(svg)).png({ quality: 90 }).toFile(out)
    console.info(`wrote ${path.relative(process.cwd(), out)}`)
}

await writeFile(
    path.join(OUT, "README.txt"),
    "Placeholder cover art generated by scripts/make-placeholders.mjs.\n" +
        "Not real work. Replace with Pamudi's own images and delete the generator.\n",
)
